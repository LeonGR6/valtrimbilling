export const activityTypeOptions = [
  {
    value: 'EXT',
    label: 'EXT FRAMES',
    description: 'Exterior frames',
    tone: 'ext',
  },
  {
    value: 'DM',
    label: 'DM',
    description: 'Drywall material',
    tone: 'dm',
  },
  {
    value: 'HW',
    label: 'Hardware',
    description: 'Hardware phase',
    tone: 'hw',
  },
]

export const activityTypeMap = Object.fromEntries(
  activityTypeOptions.map((type) => [type.value, type]),
)

function makeEvent({
  id,
  groupId = id,
  activityType,
  lotStart,
  lotEnd,
  date,
  builder,
  community,
  phase,
  building,
  notes = '',
  splitPhase = false,
  splitParts = [],
  installOnly = false,
  installDate = '',
  variant = 'base',
}) {
  const lots = lotStart === lotEnd ? `Lot ${lotStart}` : `Lots ${lotStart}–${lotEnd}`
  const type = activityTypeMap[activityType]

  return {
    id,
    groupId,
    title: `${type.label} • ${lots}`,
    start: date,
    allDay: true,
    extendedProps: {
      groupId,
      activityType,
      lotStart,
      lotEnd,
      builder,
      community,
      phase,
      building,
      notes,
      splitPhase,
      splitParts,
      installOnly,
      installDate,
      variant,
    },
  }
}

