import { getCustomerServiceClock, toIsoDate } from '../utils/dates.js'
import { prototypeTechnicians } from './prototypeTechnicians.js'

function addDays(dayOffset) {
  const value = new Date(`${getCustomerServiceClock().date}T12:00:00`)
  value.setDate(value.getDate() + dayOffset)
  return toIsoDate(value)
}

